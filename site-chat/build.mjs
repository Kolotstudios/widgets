// node site-chat/build.mjs  ->  site-chat/dist/worker.js (one ES module to paste/upload to Cloudflare)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const widget = readFileSync(join(here, 'widget.js'), 'utf8');
writeFileSync(join(here, 'widget.gen.js'), '// generated by build.mjs from widget.js - do not edit\nexport const WIDGET_JS = ' + JSON.stringify(widget) + ';\n');
const strip = (s) => s.replace(/^import .*$/gm, '').replace(/^export (const|default)/gm, (m, k) => (k === 'default' ? 'export default' : 'const'));
const out = ['// KOLOT site chat - bundled by site-chat/build.mjs. Source: Kolotstudios/widgets site-chat/', strip(readFileSync(join(here, 'channel.js'), 'utf8')), strip(readFileSync(join(here, 'widget.gen.js'), 'utf8')), strip(readFileSync(join(here, 'worker.js'), 'utf8'))].join('\n');
mkdirSync(join(here, 'dist'), { recursive: true });
writeFileSync(join(here, 'dist', 'worker.js'), out);
console.log('dist/worker.js', out.length, 'chars');
